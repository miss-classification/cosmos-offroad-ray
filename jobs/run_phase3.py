"""Phase 3 (user approved 2026-11-18 about 16:30): 10 new conditions (configs/conditions_v3.yaml) on the
9 showcase scenes, seed 101, with the realism setting chosen in phase 2. Limits raised by the user to
3.5 h GPU-phase wall time and 600 generation attempts. Submitted as Ray Jobs on the existing
workspace cluster (no new cloud resources): two generation jobs of 5 conditions each, then one
blind VLM judge job. Waits for jobs/run_phase2.py first.

Progress: /mnt/cluster_storage/cosmos-offroad/logs/run_phase3.log, run_phase3_state.json
Ray Jobs: `ray job list`, or the Jobs tab of the Ray dashboard (submission ids offroad-v3-*).
"""
from __future__ import annotations

import json
import subprocess
import sys
import time
from pathlib import Path

import yaml

PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT / "src"))
PY = str(PROJECT / ".venv" / "bin" / "python")
RAY = "/home/ray/anaconda3/bin/ray"
ROOT = Path("/mnt/cluster_storage/cosmos-offroad")
LOGS = ROOT / "logs"
STATE = LOGS / "run_phase3_state.json"
LIMIT_H = 4.0  # raised 3.5 -> 4.0 by the user (2026-11-18 16:40)
UNCOUNTED_H = 0.12
BATCHES = {
    "v3a": ["dust_brownout", "golden_hour_glare", "blizzard_whiteout", "wildfire_smoke", "night_rain"],
    "v3b": ["blue_hour_dusk", "autumn", "flooded_mud", "frost_dawn", "drought_summer"],
}
state: dict = {"started": time.strftime("%Y-%m-%d %H:%M:%S"), "steps": []}


def log(msg):
    print(f"{time.strftime('%H:%M:%S')} {msg}", flush=True)


def save(step, **kw):
    state["steps"].append({"step": step, "t": time.strftime("%H:%M:%S"), **kw})
    STATE.write_text(json.dumps(state, indent=1, default=str))


def used_h():
    from offroad_ray.reporting.benchmark import budget_status
    return budget_status()["gpu_phase_wall_time_h"]["used"] + UNCOUNTED_H


def fits(step, est_min):
    u = used_h()
    ok = u + est_min / 60 <= LIMIT_H
    log(f"budget: used {u:.2f} h, {step} est {est_min:.0f} min -> {'run' if ok else 'SKIP'} (limit {LIMIT_H} h)")
    save(f"budget:{step}", used_h=round(u, 3), est_min=est_min, run=ok)
    return ok


def ray_job(sub_id: str, cmd: str) -> str:
    """Submit a Ray Job on this cluster and block until it finishes. Returns final status."""
    entry = f"cd {PROJECT} && {cmd}"
    log(f"ray job submit {sub_id}: {cmd}")
    r = subprocess.run([RAY, "job", "submit", "--no-wait", "--submission-id", sub_id, "--", "bash", "-c", entry],
                       capture_output=True, text=True)
    if r.returncode:
        log(f"  submit failed: {r.stderr[-1000:]}")
        return "SUBMIT_FAILED"
    while True:
        time.sleep(30)
        s = subprocess.run([RAY, "job", "status", sub_id], capture_output=True, text=True).stdout
        for st in ("SUCCEEDED", "FAILED", "STOPPED"):
            if st.lower() in s.lower():
                logs = subprocess.run([RAY, "job", "logs", sub_id], capture_output=True, text=True).stdout
                (LOGS / f"{sub_id}.log").write_text(logs)
                log(f"  {sub_id}: {st} (logs {LOGS / f'{sub_id}.log'})")
                return st


def main():
    while subprocess.run(["pgrep", "-f", "jobs/run_phase2.py"], capture_output=True).returncode == 0:
        time.sleep(30)
    log("phase 2 finished")
    winner_file = PROJECT / "results/realism/sweep_scores.json"
    winner = json.loads(winner_file.read_text())["winner"] if winner_file.exists() else "pilot"
    base = yaml.safe_load((PROJECT / f"configs/{winner}.yaml").read_text()) if winner != "pilot" else {}
    control = base.get("control", {"preset_edge_threshold": "medium"})
    weights = base.get("generation", {}).get("control_weights", [1.0])
    log(f"using setting from {winner}: control={control} control_weights={weights}")
    save("setting", winner=winner, control=control, control_weights=weights)

    main_cfg = yaml.safe_load((PROJECT / "configs/main.yaml").read_text())
    allconds = yaml.safe_load((PROJECT / "configs/conditions_v3.yaml").read_text())["conditions"]
    stamp = time.strftime("%H%M%S")
    for name, conds in BATCHES.items():
        cfile = PROJECT / f"configs/conditions_{name}.yaml"
        cfile.write_text("# Generated by jobs/run_phase3.py from conditions_v3.yaml\n" +
                         yaml.safe_dump({"conditions": [c for c in allconds if c["name"] in conds]}, sort_keys=False))
        cfg = {"name": f"conditions_{name}", "dataset": main_cfg["dataset"], "clips": main_cfg.get("clips", {"clips_per_run": 3}),
               "max_clips": 9, "control": control,
               "generation": {"conditions_file": cfile.name, "seeds": [101], "control_weights": weights},
               "scheduler": {"num_actors": 8}, "budget": {"max_generation_attempts": 600}}
        (PROJECT / f"configs/conditions_{name}_run.yaml").write_text(
            f"# Generated by jobs/run_phase3.py: new conditions batch {name}, setting from {winner}. Guardrails ON.\n"
            + yaml.safe_dump(cfg, sort_keys=False))

    # prepare (CPU; cached if the showcase_v2 catalog already exists for this setting)
    with open(LOGS / "prepare_v3.log", "w") as f:
        subprocess.call([PY, "-m", "offroad_ray.cli", "prepare", "configs/conditions_v3a_run.yaml"],
                        stdout=f, stderr=subprocess.STDOUT, cwd=str(PROJECT))

    done = {}
    for name in BATCHES:
        if not fits(f"generate_{name}", 11):
            continue
        st = ray_job(f"offroad-v3-{name}-{stamp}",
                     f"{PY} -m offroad_ray.cli generate configs/conditions_{name}_run.yaml")
        save(f"generate_{name}", status=st)
        ns = ROOT / f"runs/conditions_{name}/main"
        if (ns / "pool_summary.json").exists():
            done[name] = ns

    if done and fits("judge_v3", 8):
        nsargs = " ".join(f"{k}={v}" for k, v in done.items())
        st = ray_job(f"offroad-v3-judge-{stamp}",
                     f"{PY} -m offroad_ray.cli judge configs/main.yaml --gpus 8 --out {ROOT}/runs/judge/v3 --ns {nsargs}")
        save("judge_v3", status=st)

    # showcase GIFs for the new conditions (CPU, local ffmpeg)
    for name, ns in done.items():
        with open(LOGS / f"showcase_{name}.log", "w") as f:
            subprocess.call([PY, "jobs/build_showcase.py", str(ns)], stdout=f, stderr=subprocess.STDOUT, cwd=str(PROJECT))
        save(f"showcase_{name}")
    from offroad_ray.reporting.benchmark import budget_status
    save("budget_final", **budget_status())
    log("phase 3 done")
    save("done")


if __name__ == "__main__":
    main()
